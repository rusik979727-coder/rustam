// ---------- Интерполяция көмекшілері ----------
const EASE = {
  linear: (x) => x,
  smooth: (x) => x * x * (3 - 2 * x),
  in: (x) => x * x * x,
  out: (x) => 1 - Math.pow(1 - x, 3),
  inout: (x) => (x < 0.5 ? 4 * x * x * x : 1 - Math.pow(-2 * x + 2, 3) / 2),
  step: () => 0,
};

// keys: [[t, value, ease?], ...]; value — сан немесе сандар массиві.
// Келесі кілтке дейінгі ease сол кілттің 3-элементімен беріледі.
export function track(keys) {
  return (t) => {
    if (t <= keys[0][0]) return keys[0][1];
    for (let i = 0; i < keys.length - 1; i++) {
      const [t0, v0, e] = keys[i];
      const [t1, v1] = keys[i + 1];
      if (t < t1) {
        const span = t1 - t0;
        const x = span <= 1e-6 ? 1 : (t - t0) / span;
        const k = EASE[e || 'smooth'](x);
        if (Array.isArray(v0)) return v0.map((a, j) => a + (v1[j] - a) * k);
        return v0 + (v1 - v0) * k;
      }
    }
    return keys[keys.length - 1][1];
  };
}

export const clamp01 = (x) => Math.max(0, Math.min(1, x));
export const win = (t, a, b) => clamp01((t - a) / (b - a)); // 0→1 терезе
export const pulse = (t, a, b, fade = 0.15) => Math.min(win(t, a, a + fade), 1 - win(t, b - fade, b));

